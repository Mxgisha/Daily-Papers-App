/**
 * Regenerate the WebView reader stylesheet from the validated spike CSS.
 *
 * `reader/static/reader.css` is the stylesheet that was verified against a real 390x844
 * viewport with zero page-level overflow. A React Native WebView needs it as a JavaScript
 * string, and hand-copying it would guarantee the two drift apart. So it is generated.
 *
 *   node scripts/gen-reader-css.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, '..', '..', 'reader', 'static', 'reader.css');
const TARGET = join(HERE, '..', 'src', 'platform', 'readerCss.generated.ts');

const css = readFileSync(SOURCE, 'utf-8');

// The spike CSS styles a full document; inside the app the WebView hosts arXiv's own page,
// so the site chrome has to be hidden too and the fixed toolbar replaced by native chrome.
const OVERRIDES = `
/* --- injected by the app --- */
body { padding: 0.75rem 0 3rem !important; }
.ltx_page_header, .ltx_page_footer, #header, #footer, .arxiv-header, .arxiv-footer,
.ltx_page_logo, #watermark-tr, #watermark-bl, .ltx_bib_list + .ltx_page_footer {
  display: none !important;
}
`;

if (css.includes('</style>')) {
  throw new Error('stylesheet contains </style>; it cannot be safely inlined');
}

const banner = `/* AUTO-GENERATED by scripts/gen-reader-css.mjs from reader/static/reader.css.
 * Do not edit by hand. Edit the spike stylesheet and regenerate.
 */`;

writeFileSync(
  TARGET,
  `${banner}\nexport const READER_CSS = ${JSON.stringify(css + OVERRIDES)};\n`,
);

console.log(`wrote ${TARGET} (${(css.length / 1024).toFixed(1)} KB of CSS)`);
